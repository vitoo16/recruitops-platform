import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDir, '../..');
const infraEnvPath = resolve(root, 'infra/docker/.env.local');
const apiEnvPath = resolve(root, '.env');
const webEnvPath = resolve(root, 'apps/web/.env.local');

function randomSecret(bytes = 32) {
  return randomBytes(bytes).toString('base64url');
}

function parseEnv(content) {
  return Object.fromEntries(
    content
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith('#'))
      .map((line) => {
        const index = line.indexOf('=');
        return index === -1 ? [line, ''] : [line.slice(0, index), line.slice(index + 1)];
      }),
  );
}

mkdirSync(dirname(infraEnvPath), { recursive: true });

if (!existsSync(infraEnvPath)) {
  writeFileSync(
    infraEnvPath,
    [
      '# Generated by pnpm infra:setup. Never commit this file.',
      'MINIO_ROOT_USER=recruitops_local',
      `MINIO_ROOT_PASSWORD=${randomSecret()}`,
      'MINIO_BUCKET=recruitops-private',
      '',
    ].join('\n'),
    { mode: 0o600 },
  );
  console.log('Created infra/docker/.env.local with random local MinIO credentials.');
}

if (!process.argv.includes('--infra-only')) {
  const infraEnv = parseEnv(readFileSync(infraEnvPath, 'utf8'));

  if (!existsSync(apiEnvPath)) {
    writeFileSync(
      apiEnvPath,
      [
        '# Generated local-development environment. Never commit this file.',
        'NODE_ENV=development',
        'PORT=4000',
        'CORS_ORIGINS=http://localhost:3000',
        'DATABASE_URL=postgresql://recruitops:recruitops@localhost:5432/recruitops?schema=public',
        'REDIS_URL=redis://localhost:6379',
        'STORAGE_ENDPOINT=http://localhost:9000',
        'STORAGE_REGION=us-east-1',
        `STORAGE_BUCKET=${infraEnv.MINIO_BUCKET}`,
        `STORAGE_ACCESS_KEY_ID=${infraEnv.MINIO_ROOT_USER}`,
        `STORAGE_SECRET_ACCESS_KEY=${infraEnv.MINIO_ROOT_PASSWORD}`,
        `AUTH_SECRET=${randomSecret()}`,
        '',
      ].join('\n'),
      { mode: 0o600 },
    );
    console.log('Created root .env for local API development.');
  }

  if (!existsSync(webEnvPath)) {
    writeFileSync(webEnvPath, 'NEXT_PUBLIC_API_URL=http://localhost:4000/api\n', { mode: 0o600 });
    console.log('Created apps/web/.env.local for local frontend development.');
  }
}

console.log('Local infrastructure environment is ready. Existing env files were left unchanged.');
